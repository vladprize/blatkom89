// Assembles deploy/ — a prebuilt, dependency-free bundle for PaaS hosts (Render, any Node.js host):
//   deploy/server.js, db-cli.js, admin-cli.js   bundled server + CLIs (Node.js only, no npm install)
//   deploy/migrations/                          SQL migrations (applied automatically on start)
//   deploy/public/                              production web client (served by the same process)
//   deploy/package.json, deploy/.node-version   start command and Node.js version for the host
// Usage: node tools/build-deploy.mjs           (runs the web production build and the server build first)
// The folder is committed so the host only has to run `node server.js` (see render.yaml, docs/DEPLOYMENT.md).
import { spawnSync } from 'node:child_process';
import { cpSync, existsSync, mkdirSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const out = join(root, 'deploy');
const run = (args) => {
  const r = spawnSync(process.execPath, args, { cwd: root, stdio: 'inherit' });
  if (r.status !== 0) process.exit(r.status ?? 1);
};
if (!process.argv.includes('--skip-build')) {
  run(['apps/web/build.mjs', '--mode=production']);
  run(['apps/server/build.mjs']);
}
const serverDist = join(root, 'apps/server/dist');
const webDist = join(root, 'apps/web/dist');
for (const d of [serverDist, webDist]) if (!existsSync(d)) throw new Error(`missing ${d} — build first`);

rmSync(out, { recursive: true, force: true });
mkdirSync(out, { recursive: true });
cpSync(serverDist, out, { recursive: true, filter: (src) => !src.endsWith('.map') && !src.endsWith('package.json') });
cpSync(webDist, join(out, 'public'), { recursive: true });
const version = JSON.parse(readFileSync(join(root, 'apps/server/package.json'), 'utf8')).version;
writeFileSync(
  join(out, 'package.json'),
  JSON.stringify(
    {
      name: 'blatkom89-server',
      version,
      private: true,
      description: 'BLATKOM ’89 — prebuilt server + web client (generated by tools/build-deploy.mjs, do not edit)',
      type: 'module',
      engines: { node: '>=22.12' },
      scripts: { start: 'node server.js', migrate: 'node db-cli.js migrate', 'admin:create': 'node admin-cli.js create' },
    },
    null,
    2,
  ) + '\n',
);
writeFileSync(join(out, '.node-version'), '22\n');
writeFileSync(
  join(out, 'README.md'),
  `# deploy/ — generated, do not edit

Prebuilt BLATKOM ’89 server and web client produced by \`node tools/build-deploy.mjs\` from the sources
in this repository. It needs only Node.js ≥ 22.12 and PostgreSQL: \`node server.js\` migrates the
database and serves the game, the API, \`/admin\` and the WebSocket endpoint on \`PORT\`.
Configuration is environment variables (see \`.env.example\` in the repository root and
\`docs/DEPLOYMENT.md\`); \`render.yaml\` in the repository root deploys it to Render.
`,
);

let bytes = 0;
let files = 0;
const walk = (d) => {
  for (const e of readdirSync(d)) {
    const f = join(d, e);
    const st = statSync(f);
    if (st.isDirectory()) walk(f);
    else {
      bytes += st.size;
      files++;
    }
  }
};
walk(out);
console.log(`[deploy] ${out}: ${files} files, ${(bytes / 1024 / 1024).toFixed(2)} MB`);
