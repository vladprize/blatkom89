/** District-style nickname suggestions («Тихий Завхоз», «Фартовый Енот»): adjective + noun, ≤ 24 chars. */
const ADJ = ['Тихий', 'Гаражный', 'Заводской', 'Ночной', 'Хмурый', 'Бывалый', 'Весёлый', 'Дворовый', 'Импортный', 'Фартовый', 'Кассетный', 'Районный', 'Неуловимый', 'Деловой', 'Сонный', 'Лысый'];
const NOUN = ['Завхоз', 'Вахтёр', 'Кладовщик', 'Физрук', 'Бригадир', 'Таксист', 'Электрик', 'Слесарь', 'Прораб', 'Кооператор', 'Сантехник', 'Киномеханик', 'Фарцовщик', 'Почтальон', 'Дворник', 'Барсук', 'Енот', 'Хорёк', 'Бобр', 'Филин', 'Сыч'];

export function randomNickname(rnd: () => number = Math.random): string {
  const pick = <T>(a: readonly T[]) => a[Math.floor(rnd() * a.length) % a.length]!;
  return `${pick(ADJ)} ${pick(NOUN)}`;
}
